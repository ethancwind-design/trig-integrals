"""Crops the 25 Quiz 4 practice problems out of build/src/quiz-4-practice-problems.pdf into img/q/q4-NN.webp
and merges them into shots.js (the manifest the lessons read for the "Original question" button).

    python3 build/q4shots.py          # needs poppler (pdftoppm, pdftotext) and Pillow, numpy

build/shots.py keeps these q4-* entries when it regenerates shots.js.
"""
import json, os, re, subprocess, tempfile
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PDF = os.path.join(ROOT, 'build', 'src', 'quiz-4-practice-problems.pdf')
OUT = os.path.join(ROOT, 'img', 'q')
os.makedirs(OUT, exist_ok=True)
tmp = tempfile.mkdtemp()
DPI, PAD, MAXW, FOOT = 200, 18, 1000, 736   # FOOT: points from the top where the page number starts (cropped away)
S = DPI / 72
N = 25

subprocess.run(['pdftotext', '-bbox', PDF, os.path.join(tmp, 'b.html')], check=True)
pages = re.split(r'<page ', open(os.path.join(tmp, 'b.html')).read())[1:]
marks = []   # (page index, y, number)
for i, pg in enumerate(pages):
    for x, y, w in re.findall(r'<word xMin="([\d.]+)" yMin="([\d.]+)" xMax="[\d.]+" yMax="[\d.]+">(\d+)\.</word>', pg):
        if float(x) < 100 and int(w) == len(marks) + 1:
            marks.append((i, float(y), int(w)))
assert len(marks) == N, len(marks)
subprocess.run(['pdftoppm', '-r', str(DPI), '-png', PDF, os.path.join(tmp, 'p')], check=True)
img = {i: Image.open(os.path.join(tmp, f'p-{i + 1}.png')).convert('RGB') for i in range(len(pages))}

manifest = {}
for k, (pg, y, num) in enumerate(marks):
    top = y - 8
    nxt = marks[k + 1] if k + 1 < N else (pg + 1, 0, 0)
    parts = []
    for p in range(pg, min(nxt[0], len(pages) - 1) + 1):
        t = top if p == pg else 0
        b = (nxt[1] - 8) if p == nxt[0] else FOOT
        if b <= t:
            continue
        reg = img[p].crop((int(60 * S), int(t * S), int(570 * S), int(b * S)))
        a = np.asarray(reg.convert('L')); ys, xs = np.where(a < 235)
        if len(ys) == 0:
            continue
        parts.append(reg.crop((max(xs.min() - PAD, 0), max(ys.min() - PAD, 0), min(xs.max() + PAD, reg.width), min(ys.max() + PAD, reg.height))))
    w = max(q.width for q in parts)
    canvas = Image.new('RGB', (w, sum(q.height for q in parts)), 'white')
    yy = 0
    for q in parts:
        canvas.paste(q, (0, yy)); yy += q.height
    if canvas.width > MAXW:
        canvas = canvas.resize((MAXW, round(canvas.height * MAXW / canvas.width)), Image.LANCZOS)
    key = f'q4-{num:02d}'
    canvas.save(os.path.join(OUT, key + '.webp'), 'WEBP', quality=86, method=6)
    manifest[key] = {'f': f'img/q/{key}.webp', 'w': canvas.width, 'h': canvas.height, 'alt': f'Quiz 4 practice problem {num} as it appears in the source PDF'}

old = os.path.join(ROOT, 'shots.js')
t = open(old).read()
cur = json.loads(t[t.index('{'):t.rindex('}') + 1])
cur = {k: v for k, v in cur.items() if not k.startswith('q4-')}
cur.update(manifest)
with open(old, 'w') as f:
    f.write('/* generated by build/shots.py: crops of the source PDF, keyed by problem */\nwindow.SHOTS=' + json.dumps(cur, separators=(',', ':'), ensure_ascii=False) + ';\n')
print(len(manifest), 'Quiz 4 crops;', len(cur), 'entries in shots.js')
